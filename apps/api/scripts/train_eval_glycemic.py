"""Train and evaluate the synthetic post-meal glucose model; print and save a report.

    uv run --project apps/api python apps/api/scripts/train_eval_glycemic.py

Writes output/glycemic_model_eval.md at the repo root. All data is simulated by
apps/api/ml/glycemic_response.py; read its docstring before quoting any number. No model
file is written: training takes about a second, so the script retrains every time.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from ml.glycemic_response import FEATURES, evaluate  # noqa: E402

OUT = Path(__file__).resolve().parents[3] / "output" / "glycemic_model_eval.md"


def main() -> None:
    r = evaluate()
    b, g = r["carb_baseline"], r["gradient_boosting"]
    lines = [
        "# Synthetic post-meal glucose model: evaluation",
        "",
        "Generated by `apps/api/scripts/train_eval_glycemic.py`. **All data is simulated** by",
        "`apps/api/ml/glycemic_response.py`, so these scores only show that the model recovers",
        "effects the simulator was written to contain. They say nothing about accuracy on real",
        "people. This is a workflow demonstration, not a validated or clinical model.",
        "",
        f"Target: peak glucose rise within 2 h of a meal (mg/dL). Features: {', '.join(FEATURES)}.",
        f"Split: {r['rows_train']} training meals; {r['rows_test']} test meals from "
        f"{r['people_test']} held-out people (grouped by person). Seed {r['seed']}.",
        "",
        "| Model | MAE (mg/dL) | R² | Pearson r |",
        "|---|---|---|---|",
        f"| Carb counting (linear on carbs only) | {b['mae_mg_dl']} | {b['r2']} | {b['pearson_r']} |",
        f"| Gradient boosting (HistGradientBoosting, all features) | {g['mae_mg_dl']} | "
        f"{g['r2']} | {g['pearson_r']} |",
        "",
        "Permutation importance on the test people (drop in R² when a feature is shuffled):",
        "",
        *[f"- {name}: {value}" for name, value in r["permutation_importance"]],
        "",
    ]
    text = "\n".join(lines)
    print(text)
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
